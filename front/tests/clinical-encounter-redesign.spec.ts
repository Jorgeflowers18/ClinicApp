    await expect(page.locator('.clinic-encounter-exams').first().locator('[role="radio"][data-value="normal"][aria-checked="true"]')).toHaveCount(6)
    await openEncounterGroup(page, "intraoral")
    await expect(radio(page, "Oclusión", "No evaluado")).toHaveAttribute("aria-checked", "true")
    await step(page, 5).click()
    await expect(page.getByRole("form", { name: "Revisión" })).toContainText("ASA II")
