    await expect(radio(page, "Clasificación ASA", "ASA II")).toBeFocused()
    await expect(radio(page, "Clasificación ASA", "ASA II")).toHaveAttribute("aria-checked", "true")
    await openEncounterGroup(page, "vitals")
    await page.getByLabel("Peso (kg)", { exact: true }).fill("70")
    await page.getByLabel("Talla (cm)", { exact: true }).fill("175")
    await expect(page.getByLabel("IMC calculado")).toHaveText("22.9")
    await page.getByLabel("FC (lpm)", { exact: true }).fill("500")
    await page.getByRole("button", { name: "Siguiente", exact: true }).click()
    await expect(page.getByText("Valor entre 30 y 220", { exact: true })).toBeVisible()
    await page.getByLabel("FC (lpm)", { exact: true }).fill("72")
    await openEncounterGroup(page, "risk")
    await page.getByRole("checkbox", { name: "Interconsulta requerida", exact: true }).click()
    await page.getByLabel("Especialista o motivo de la interconsulta", { exact: true }).fill("Consulta de prueba")
    await page.getByRole("button", { name: "Siguiente", exact: true }).click()
    const untouched = radio(page, "Simetría facial", "No evaluado")
    await expect(untouched).toHaveAttribute("aria-checked", "true")
    const neutral = await untouched.evaluate(node => getComputedStyle(node).backgroundColor)
    await expect(untouched).not.toHaveCSS("background-color", theme === "dark" ? "rgb(228, 242, 34)" : "rgb(83, 80, 204)")
    await radio(page, "ATM / ruidos / dolor", "Alterado").click()
