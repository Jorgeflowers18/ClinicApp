import { expect, test, type Page } from "@playwright/test"
import { clinicalNavigation, selectRecordSection } from "./helpers/clinical-navigation"

test.use({ timezoneId: "America/Guayaquil" })

async function login(page: Page, theme: "light" | "dark", route: string) {
  await page.clock.install({ time: new Date("2026-11-11T17:00:00Z") })
  await page.goto("/login")
  await page.getByRole("button", { name: theme === "light" ? "Tema claro" : "Tema oscuro", exact: true }).click()
  await page.locator("#email").fill("admin@clinica.com")
  await page.locator("#password").fill("admin123")
  await page.getByRole("button", { name: "Ingresar", exact: true }).click()
  await page.getByRole("button", { name: "Continuar", exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto(route)
  await expect(page.locator('[data-slot="skeleton"]')).toHaveCount(0)
}

for (const theme of ["light", "dark"] as const) {
  for (const count of [0, 1, 4, 20, 30]) {
    test(`record pagination derives real pages for ${count} rows in ${theme}`, async ({ page }) => {
      await page.goto(`/tests/fixtures/pagination.html?rows=${count}&theme=${theme}`)
      await expect(page.getByRole("heading")).toBeVisible()
      const pages = Math.ceil(count / 10)
      if (!pages) {
        await expect(page.getByText("Sin resultados", { exact: true })).toBeVisible()
        await expect(page.locator('[data-slot="pagination-bar"]')).toHaveCount(0)
      } else for (let current = 1; current <= pages; current++) {
        await expect(page.getByRole("button", { name: "Anterior", exact: true, includeHidden: true })).toHaveCount(current > 1 ? 1 : 0)
        await expect(page.getByRole("button", { name: "Siguiente", exact: true, includeHidden: true })).toHaveCount(current < pages ? 1 : 0)
        await expect(page.locator('[data-slot="pagination-bar"]')).toContainText(`Mostrando ${(current - 1) * 10 + 1}-${Math.min(current * 10, count)} de ${count}`)
        await expect(page.getByRole("navigation", { name: "Paginación de registros" })).toHaveCount(pages > 1 ? 1 : 0)
        if (current < pages) await page.getByRole("button", { name: "Siguiente", exact: true }).click()
      }
      await expect(page.getByText("Página 1 de 1", { exact: true })).toHaveCount(0)
      await expect(page.getByText("Página 1 de 0", { exact: true })).toHaveCount(0)
      await expect(page.getByLabel("Envíos involuntarios")).toHaveText("0")
    })
  }

  test(`record pagination clamps filters, page size and removed results in ${theme}`, async ({ page }) => {
    await page.goto(`/tests/fixtures/pagination.html?rows=30&page=3&theme=${theme}`)
    await expect(page.getByText("Página 3 de 3", { exact: true })).toBeVisible()
    await page.getByLabel("Registros", { exact: true }).fill("11")
    await expect(page.getByLabel("Página activa")).toHaveText("2")
    await expect(page.locator('[data-slot="pagination-bar"]')).toContainText("Mostrando 11-11 de 11")
    await page.getByLabel("Tamaño de página", { exact: true }).selectOption("30")
    await expect(page.getByLabel("Página activa")).toHaveText("1")
    await expect(page.getByRole("navigation")).toHaveCount(0)
    await page.getByLabel("Búsqueda", { exact: true }).fill("inexistente")
    await expect(page.getByText("Sin resultados", { exact: true })).toBeVisible()
    await expect(page.locator('[data-slot="pagination-bar"]')).toHaveCount(0)
    await page.getByLabel("Búsqueda", { exact: true }).fill("Registro 1")
    await expect(page.locator('[data-slot="pagination-bar"]')).toContainText("Mostrando 1-3 de 3")
    await expect(page.getByLabel("Envíos involuntarios")).toHaveText("0")
  })

  test(`treatments preserve search and amounts without a single-page pager in ${theme}`, async ({ page }) => {
    await login(page, theme, "/tratamientos")
    await expect(page.locator('[data-slot="pagination-bar"]')).toContainText("Mostrando 1-4 de 4")
    await expect(page.getByRole("navigation", { name: "Paginación de registros" })).toHaveCount(0)
    await page.getByRole("textbox", { name: "Buscar tratamientos", exact: true }).fill("Resina")
    await expect(page.locator('[data-slot="pagination-bar"]')).toContainText("Mostrando 1-1 de 1")
    await expect(page.getByRole("cell", { name: "$55,00", exact: true })).toBeVisible()
    await page.getByRole("textbox", { name: "Buscar tratamientos", exact: true }).fill("sin coincidencias")
    await expect(page.locator('[data-slot="pagination-bar"]')).toHaveCount(0)
    await expect(page.getByRole("region", { name: "Tabla desplazable horizontalmente", exact: true }).getByText("Sin tratamientos", { exact: true })).toBeVisible()
  })

  test(`clinical summary and grouped sections remain compact, informative and independent in ${theme}`, async ({ page }) => {
    await login(page, theme, "/historial-clinico/paciente/pat_1")
    await expect(page.getByRole("button", { name: "Registrar atención", exact: true })).toBeEnabled()
    await expect(clinicalNavigation(page)).toContainText("Sección 3 de 9")
    const cards = page.locator(".clinic-kpi-card")
    await expect(cards).toHaveCount(4)
    for (const card of await cards.all()) {
      const bounds = await card.boundingBox()
      expect(bounds!.height).toBeGreaterThanOrEqual(64)
      expect(bounds!.height).toBeLessThanOrEqual(122)
      const label = await card.locator(".clinic-kpi-label").boundingBox()
      const value = await card.locator(".clinic-kpi-value").boundingBox()
      expect(value!.y - label!.y - label!.height).toBeGreaterThanOrEqual(4)
      expect(value!.y - label!.y - label!.height).toBeLessThanOrEqual(8)
      await expect(card.getByRole("button")).toHaveCount(0)
      expect(await card.evaluate((node) => getComputedStyle(node).cursor)).not.toBe("pointer")
    }
    await expect(page.getByRole("note")).toContainText("no se sincroniza con un servidor")
    await clinicalNavigation(page).getByRole("button", { name: "Ver secciones", exact: true }).click()
    await expect(page.getByRole("menu").getByText("Secciones clínicas", { exact: true })).toBeVisible()
    await expect(page.getByRole("menu").getByText("Adicional", { exact: true })).toBeVisible()
    const bounds = await page.getByRole("menu").boundingBox()
    expect(bounds!.height).toBeLessThanOrEqual(320)
    await expect(page.getByRole("menuitemradio", { name: "10. Evolución periodontal", exact: true })).toHaveCount(0)
    await page.getByRole("menuitemradio", { name: "Evolución periodontal", exact: true }).click()
    await expect(clinicalNavigation(page)).toContainText("Sección adicional")
    await expect(page.getByRole("group", { name: "Navegación entre secciones", includeHidden: true })).toHaveCount(0)
    await selectRecordSection(page, "Citas")
    await expect(clinicalNavigation(page)).toContainText("Sección 9 de 9")
    await expect(page.getByRole("button", { name: "Siguiente", exact: true, includeHidden: true })).toHaveCount(0)
    await selectRecordSection(page, "Datos del paciente")
    await expect(clinicalNavigation(page)).toContainText("Sección 1 de 9")
    await expect(page.getByRole("button", { name: "Anterior", exact: true, includeHidden: true })).toHaveCount(0)
  })

  test(`calendar keeps all times, date navigation, appointments, blocks and slot selection in ${theme}`, async ({ page }) => {
    await login(page, theme, "/citas")
    const calendar = page.locator(".clinic-appointments-calendar")
    const toolbar = calendar.locator(".rbc-toolbar")
    await expect(page.getByLabel("Profesional", { exact: true })).toContainText("Todos los profesionales")
    await expect(toolbar.getByRole("button", { name: "Semana", exact: true })).toHaveClass(/rbc-active/)
    expect(await toolbar.getByRole("button", { name: "Semana", exact: true }).evaluate((node) => getComputedStyle(node).backgroundColor)).not.toBe(theme === "dark" ? "rgb(228, 242, 34)" : "rgb(83, 80, 204)")
    const times = await calendar.locator(".rbc-time-gutter .rbc-label").allTextContents()
    expect(times).toContain("00:00")
    expect(times).toContain("23:00")
    await expect.poll(() => calendar.locator(".rbc-time-content").evaluate((node) => node.scrollTop)).toBeGreaterThan(0)
    const range = await toolbar.locator(".rbc-toolbar-label").textContent()
    await toolbar.getByRole("button", { name: "Sig.", exact: true }).click()
    await expect(toolbar.locator(".rbc-toolbar-label")).not.toHaveText(range!)
    await toolbar.getByRole("button", { name: "Ant.", exact: true }).click()
    await expect(toolbar.locator(".rbc-toolbar-label")).toHaveText(range!)
    for (const name of ["Mes", "Día", "Semana"]) {
      await toolbar.getByRole("button", { name, exact: true }).click()
      await expect(toolbar.getByRole("button", { name, exact: true })).toHaveClass(/rbc-active/)
    }
    await toolbar.getByRole("button", { name: "Hoy", exact: true }).click()
    await page.getByRole("button", { name: "Nueva cita", exact: true }).click()
    let dialog = page.getByRole("dialog", { name: "Nueva cita", exact: true })
    await dialog.getByLabel("Paciente", { exact: true }).click()
    await page.getByRole("option", { name: /Valentina Suárez/ }).click()
    await dialog.getByLabel("Profesional", { exact: true }).click()
    await page.getByRole("option", { name: /Dra\. Carla Ríos/ }).click()
    await dialog.getByLabel("Fecha", { exact: true }).fill("2026-11-11")
    await dialog.getByLabel("Inicio", { exact: true }).fill("14:00")
    await dialog.getByLabel("Fin", { exact: true }).fill("14:30")
    await dialog.getByLabel("Notas", { exact: true }).fill("Comprobación de interfaz")
    await dialog.getByRole("button", { name: "Agendar cita", exact: true }).click()
    await expect(dialog).toHaveCount(0)
    const appointment = calendar.locator(".rbc-event").filter({ hasText: "Valentina Suárez" }).filter({ hasText: "14:00" })
    await expect(appointment).toHaveCount(1)
    await appointment.click()
    await page.getByRole("dialog").getByRole("button", { name: "Editar / reprogramar", exact: true }).click()
    dialog = page.getByRole("dialog", { name: "Editar cita", exact: true })
    await dialog.getByLabel("Notas", { exact: true }).fill("Nota actualizada de interfaz")
    await dialog.getByRole("button", { name: "Guardar cambios", exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await appointment.click()
    await expect(page.getByRole("dialog")).toContainText("Nota actualizada de interfaz")
    await page.getByRole("dialog").getByRole("button", { name: "Cancelar cita", exact: true }).click()
    await expect(appointment).toHaveClass(/rbc-event-cancelled/)
    await page.getByRole("dialog").locator('[data-slot="dialog-close"]').click()
    await expect(page.getByRole("dialog")).toHaveCount(0)
    await page.getByRole("button", { name: "Bloquear horario", exact: true }).click()
    dialog = page.getByRole("dialog", { name: "Bloquear horario", exact: true })
    await dialog.getByLabel("Profesional (opcional)", { exact: true }).click()
    await page.getByRole("option", { name: /Dra\. Carla Ríos/ }).click()
    await dialog.getByLabel("Fecha", { exact: true }).fill("2026-11-11")
    await dialog.getByLabel("Inicio", { exact: true }).fill("16:00")
    await dialog.getByLabel("Fin", { exact: true }).fill("17:00")
    await dialog.getByLabel("Motivo", { exact: true }).fill("Reserva visual UI")
    await dialog.locator('button[type="submit"]').click()
    await expect(dialog).toHaveCount(0)
    await expect(calendar.locator(".rbc-event-block").filter({ hasText: "Reserva visual UI" })).toHaveCount(1)
    const slot = calendar.locator(".rbc-day-slot").nth(6).locator(".rbc-time-slot").nth(18)
    await slot.scrollIntoViewIfNeeded()
    const slotBounds = await slot.boundingBox()
    expect(slotBounds).not.toBeNull()
    // RBC receives pointer input through its event overlay above the visual slot.
    await page.mouse.click(slotBounds!.x + slotBounds!.width / 2, slotBounds!.y + 2)
    dialog = page.getByRole("dialog", { name: "Nueva cita", exact: true })
    await expect(dialog).toBeVisible()
    await expect(dialog.getByLabel("Inicio", { exact: true })).toHaveValue("09:00")
    await dialog.getByRole("button", { name: "Cancelar", exact: true }).click()
  })
}
