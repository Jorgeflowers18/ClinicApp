test("original bytes, metadata, patient ownership, category archive and file restoration survive reload", async ({ page }) => {
  await loginArchive(page)
  const [id] = await seedArchive(page, 1)
  const result = await page.evaluate(async id => {
    const a = "/src/modules/clinical-history/archive/api.ts", c = "/src/modules/clinical-history/api/clinical-history.api.ts", f = "/src/modules/clinical-history/archive/lib/classification.ts"
    const [{ archiveApi }, { clinicalHistoryApi }, { fileDraft }] = await Promise.all([import(a), import(c), import(f)])
    const bytes = async (blob: Blob) => Array.from(new Uint8Array(await blob.arrayBuffer()))
    const before = await bytes(await archiveApi.original("pat_5", id))
    const initial = await clinicalHistoryApi.getRecord("pat_5"), file = initial.record.attachments.find((item: { id: string }) => item.id === id)
    const edited = await archiveApi.edit("pat_5", id, 1, { ...fileDraft(file), displayName: "Control actualizado", studyDate: null, notes: "Texto completo conservado" })
    let stale = ""; try { await archiveApi.edit("pat_5", id, 1, fileDraft(file)) } catch (error) { stale = (error as Error).message }
    const archived = await archiveApi.archive("pat_5", id, 2, true)
    let other = ""; try { await archiveApi.original("pat_1", id) } catch (error) { other = (error as Error).message }
    const catalog = await archiveApi.catalog()
    await archiveApi.category({ ...catalog.categories[0], archivedAt: new Date().toISOString() })
    const restored = await archiveApi.archive("pat_5", id, 3, false)
    const after = await bytes(await archiveApi.original("pat_5", id))
    return { before, after, stale, other, edited: edited.record.attachments.find((item: { id: string }) => item.id === id), archived: archived.record.attachments.find((item: { id: string }) => item.id === id), restored: restored.record.attachments.find((item: { id: string }) => item.id === id), chartBefore: initial.record.chart, chartAfter: restored.record.chart, encountersBefore: initial.encounters, encountersAfter: restored.encounters }
  }, id)
  expect(result.before).toEqual(result.after)
  expect(result.edited.archive.displayName).toBe("Control actualizado")
  expect(result.edited.archive.studyDate).toBeNull()
  expect(result.stale).toContain("cambió")
  expect(result.other).toContain("este paciente")
  expect(result.archived.archive.archivedAt).toBeTruthy()
  expect(result.restored.archive.archivedAt).toBeNull()
  expect(result.restored.archive.audit.map((item: { action: string }) => item.action)).toEqual(["adjuntar", "editar", "archivar", "restaurar"])
  expect(result.chartBefore).toEqual(result.chartAfter)
  expect(result.encountersBefore).toEqual(result.encountersAfter)
  await openArchive(page)
  await expect(page.getByRole("button", { name: "Control actualizado", exact: true })).toBeVisible()
  await expect(page.getByText("Sin fecha de estudio", { exact: true })).toBeVisible()
  await expect(page.getByText("Controles de prueba (archivada)", { exact: true })).toBeVisible()
})

