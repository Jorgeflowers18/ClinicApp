test("shared archive updates do not overwrite an unsaved medical draft", async ({ page }) => {
  await loginArchive(page)
  await page.goto("/historial-clinico/paciente/pat_5")
  await expect(page.frameLocator("iframe").locator("#toothGrid")).toBeVisible()
  await selectRecordSection(page, "Antecedentes")
  const textareas = page.locator('textarea:visible')
  await textareas.first().fill("Borrador médico de prueba sin guardar")
  const draftBefore = await textareas.first().inputValue()
  const [savedFileId] = await seedArchive(page, 1)
  await expect(textareas.first()).toHaveValue(draftBefore)
  await selectRecordSection(page, "Fotos y documentos")
  await expect(page.getByRole("button", { name: "Imagen de prueba 1", exact: true })).toBeVisible()
  await selectRecordSection(page, "Antecedentes")
  await expect(page.locator('textarea:visible').first()).toHaveValue(draftBefore)
  await page.getByRole("region", { name: "Cambios sin guardar", exact: true }).getByRole("button", { name: "Guardar cambios", exact: true }).click()
  await page.getByRole("alertdialog").getByRole("button", { name: "Guardar cambios", exact: true }).click()
  await expect(page.getByText("Cambios guardados en la historia clínica", { exact: true })).toBeVisible()
  const saved = await page.evaluate(async () => { const path = "/src/modules/clinical-history/api/clinical-history.api.ts"; return (await (await import(path)).clinicalHistoryApi.getRecord("pat_5")).record })
  expect(saved.attachments.some((item: { id: string }) => item.id === savedFileId)).toBeTruthy()
  expect(JSON.stringify(saved)).toContain(draftBefore)
})

test("upload partial failures, retries, outline controls and exclusive accordions", async ({ page }) => {
  await loginArchive(page, "light")
  await openArchive(page)
  await page.getByRole("button", { name: "Adjuntar archivos", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Adjuntar archivos clínicos", exact: true })
  const png = await page.evaluate(() => { const c = document.createElement("canvas"); c.width = 20; c.height = 20; c.getContext("2d")!.fillRect(0, 0, 20, 20); return c.toDataURL("image/png").split(",")[1] })
  await dialog.getByLabel("Seleccionar archivos clínicos", { exact: true }).setInputFiles([{ name: "valid.png", mimeType: "image/png", buffer: Buffer.from(png, "base64") }, { name: "fake.png", mimeType: "image/png", buffer: Buffer.from("not an image") }])
  await dialog.getByRole("button", { name: /^Clasificación clínica/ }).click()
  await dialog.getByLabel("Tipo clínico", { exact: true }).click()
  await page.getByRole("option", { name: "Fotografía clínica", exact: true }).click()
  await dialog.getByRole("button", { name: /^Información adicional/ }).click()
  await expect(dialog.getByRole("button", { name: /^Clasificación clínica/ })).toHaveAttribute("aria-expanded", "false")
  await dialog.getByRole("button", { name: "Guardar archivos", exact: true }).click()
  await expect(dialog.getByText("1 de 2 archivos guardados en el archivo clínico.", { exact: true })).toBeVisible()
  await expect(dialog.getByText(/el contenido no corresponde/)).toBeVisible()
  await dialog.getByRole("button", { name: "Guardar archivos restantes", exact: true }).click()
  await expect(dialog.getByText("1 de 2 archivos guardados en el archivo clínico.", { exact: true })).toBeVisible()
  await dialog.getByRole("button", { name: "Cancelar", exact: true }).click()
  await expect(page.getByRole("button", { name: "valid.png", exact: true })).toBeVisible()
  const count = await page.evaluate(async () => { const p = "/src/modules/clinical-history/api/clinical-history.api.ts"; return (await (await import(p)).clinicalHistoryApi.getRecord("pat_5")).record.attachments.length })
  expect(count).toBe(1)
})
