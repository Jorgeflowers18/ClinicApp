import { expect, test } from "@playwright/test"
import { archiveChoice, loginArchive, openArchive, seedArchive } from "./helpers/clinical-archive"

test.use({ timezoneId: "America/Guayaquil", reducedMotion: "reduce" })

test("metadata editing, catalog rename, category archival and file restore work from the real interface", async ({ page }) => {
  await loginArchive(page)
  await seedArchive(page, 1)
  await openArchive(page)
  await page.getByRole("button", { name: "Acciones de Imagen de prueba 1", exact: true }).click()
  await page.getByRole("menuitem", { name: "Editar información", exact: true }).click()
  const edit = page.getByRole("dialog", { name: "Editar metadatos", exact: true })
  await edit.getByLabel("Nombre del archivo", { exact: true }).fill("Nombre editado en interfaz")
  await edit.getByLabel("Fecha de estudio", { exact: true }).fill("2026-10-05")
  await edit.getByLabel("Notas clínicas del archivo", { exact: true }).fill("Notas conservadas del archivo sintético")
  await edit.getByRole("button", { name: "Guardar cambios", exact: true }).click()
  await expect(edit).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Nombre editado en interfaz", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Categorías", exact: true }).click()
  const catalog = page.getByRole("dialog", { name: "Categorías y etiquetas", exact: true })
  await catalog.getByRole("button", { name: "Editar categoría Controles de prueba", exact: true }).click()
  await catalog.getByLabel("Nombre de categoría", { exact: true }).fill("Seguimiento sintético")
  await catalog.getByRole("button", { name: "Guardar categoría", exact: true }).click()
  await expect(catalog.getByRole("button", { name: "Editar categoría Seguimiento sintético", exact: true })).toBeVisible()
  await catalog.getByRole("button", { name: "Archivar categoría Seguimiento sintético", exact: true }).click()
  await expect(catalog.getByRole("button", { name: "Restaurar categoría Seguimiento sintético", exact: true })).toBeVisible()
  await catalog.getByRole("button", { name: "Etiquetas", exact: true }).click()
  await catalog.getByRole("button", { name: "Editar etiqueta Prueba visual", exact: true }).click()
  await catalog.getByLabel("Nombre de etiqueta", { exact: true }).fill("Control de prueba")
  await catalog.getByRole("button", { name: "Guardar etiqueta", exact: true }).click()
  await expect(catalog.getByRole("button", { name: "Editar etiqueta Control de prueba", exact: true })).toBeVisible()
  await catalog.getByRole("button", { name: "Cerrar", exact: true }).last().click()
  await expect(page.getByText("Seguimiento sintético (archivada)", { exact: true })).toBeVisible()
  await expect(page.getByText("Control de prueba", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Acciones de Nombre editado en interfaz", exact: true }).click()
  await page.getByRole("menuitem", { name: "Archivar archivo", exact: true }).click()
  await page.getByRole("alertdialog").getByRole("button", { name: "Archivar archivo", exact: true }).click()
  await expect(page.getByRole("button", { name: "Nombre editado en interfaz", exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "Más filtros", exact: true }).click()
  await archiveChoice(page, "Estado del archivo", "Archivados")
  await page.getByRole("button", { name: "Acciones de Nombre editado en interfaz", exact: true }).click()
  await page.getByRole("menuitem", { name: "Restaurar archivo", exact: true }).click()
  await page.getByRole("alertdialog").getByRole("button", { name: "Restaurar archivo", exact: true }).click()
  await page.getByRole("button", { name: "Restablecer filtros", exact: true }).click()
  await expect(page.getByRole("button", { name: "Nombre editado en interfaz", exact: true })).toBeVisible()
})

test("gallery paginates metadata and only requests thumbnails for visible records", async ({ page }) => {
  test.setTimeout(120000)
  await loginArchive(page)
  await seedArchive(page, 26)
  await page.goto("/pacientes/pat_5")
  await page.getByRole("tab", { name: "Archivo clínico", exact: true }).click()
  await expect(page.getByRole("button", { name: /^Vista previa de Imagen de prueba/ })).toHaveCount(24)
  const thumbnails = () => page.evaluate(async () => { const path = "/src/shared/lib/query-client.ts", { queryClient } = await import(path); return queryClient.getQueryCache().findAll({ queryKey: ["clinical-history", "thumbnail", "pat_5"] }).filter((query: { state: { data?: Blob } }) => query.state.data instanceof Blob).map((query: { queryKey: string[] }) => query.queryKey[3]) })
  await expect.poll(async () => (await thumbnails()).length).toBeGreaterThan(0)
  const requested = await thumbnails()
  expect(requested.length).toBeLessThanOrEqual(24)
  const visibleIds = await page.locator("[data-file-id]").evaluateAll(nodes => nodes.map(node => node.getAttribute("data-file-id")))
  expect(requested.every((id: string) => visibleIds.includes(id))).toBeTruthy()
  await page.getByRole("navigation", { name: "Paginación de archivos", exact: true }).getByRole("button", { name: "Siguiente", exact: true }).click()
  await expect(page.getByRole("button", { name: /^Vista previa de Imagen de prueba/ })).toHaveCount(2)
  await page.getByRole("button", { name: "Vista de lista", exact: true }).click()
  await expect(page.getByRole("navigation", { name: "Paginación de archivos", exact: true })).toContainText("Página 2 de 2")
  await page.reload()
  await page.getByRole("tab", { name: "Archivo clínico", exact: true }).click()
  await expect(page.getByRole("columnheader", { name: "Fecha de estudio", exact: true })).toBeVisible()
})

test("fullscreen opens and closes without errors and original PDF stays in the authorized viewer", async ({ page }) => {
  await loginArchive(page)
  await seedArchive(page, 2)
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message))
  await openArchive(page)
  await page.getByRole("button", { name: "Vista previa de Imagen de prueba 1", exact: true }).click()
  const viewer = page.getByRole("dialog", { name: "Imagen de prueba 1", exact: true })
  await viewer.getByRole("button", { name: "Pantalla completa", exact: true }).click()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBeTruthy()
  await viewer.getByRole("button", { name: "Salir de pantalla completa", exact: true }).click()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBeFalsy()
  await viewer.getByRole("button", { name: "Cerrar", exact: true }).click()
  await page.getByRole("button", { name: "Acciones de Imagen de prueba 1", exact: true }).click()
  await page.getByRole("menuitem", { name: "Pantalla completa", exact: true }).click()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBeTruthy()
  await page.getByRole("dialog", { name: "Imagen de prueba 1", exact: true }).getByRole("button", { name: "Archivo anterior", exact: true }).click()
  const next = page.getByRole("dialog", { name: "Imagen de prueba 2", exact: true })
  await expect(next).toBeVisible()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBeTruthy()
  await next.getByRole("button", { name: "Cerrar", exact: true }).click()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBeFalsy()
  await page.evaluate(async () => {
    const a = "/src/modules/clinical-history/archive/api.ts", t = "/src/modules/clinical-history/archive/types.ts", q = "/src/shared/lib/query-client.ts", keys = "/src/modules/clinical-history/api/clinical-history.queries.ts"
    const [{ archiveApi }, { emptyFileDraft }, { queryClient }, { clinicalHistoryKeys }] = await Promise.all([import(a), import(t), import(q), import(keys)])
    const objects = ["<< /Type /Catalog /Pages 2 0 R >>", "<< /Type /Pages /Kids [3 0 R] /Count 1 >>", "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 300 300] /Contents 4 0 R >>", "<< /Length 0 >>\nstream\n\nendstream"]
    let pdf = "%PDF-1.4\n"; const offsets = [0]
    for (const [index, object] of objects.entries()) { offsets.push(pdf.length); pdf += `${index + 1} 0 obj\n${object}\nendobj\n` }
    const xref = pdf.length
    pdf += `xref\n0 5\n0000000000 65535 f \n${offsets.slice(1).map(offset => `${String(offset).padStart(10, "0")} 00000 n \n`).join("")}trailer\n<< /Size 5 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`
    const history = await archiveApi.attach("pat_5", new File([pdf], "informe-prueba.pdf", { type: "application/pdf" }), { ...emptyFileDraft(), displayName: "Informe sintético", clinicalType: "informe_medico" })
    queryClient.setQueryData(clinicalHistoryKeys.record("pat_5"), history)
  })
  await page.getByRole("button", { name: "Vista previa de Informe sintético", exact: true }).click()
  const pdf = page.getByRole("dialog", { name: "Informe sintético", exact: true })
  await expect(pdf.locator('object[type="application/pdf"]')).toBeVisible()
  await expect(pdf.getByRole("button", { name: "Descargar original", exact: true })).toBeEnabled()
  expect(errors).toEqual([])
})
